"""Order, fill and trade records."""
from __future__ import annotations

from dataclasses import dataclass, field
from enum import StrEnum

import pandas as pd


class OrderType(StrEnum):
    MARKET = "MARKET"
    LIMIT = "LIMIT"
    STOP = "STOP"
    STOP_LIMIT = "STOP_LIMIT"


class OrderStatus(StrEnum):
    OPEN = "OPEN"
    PARTIAL = "PARTIAL"
    FILLED = "FILLED"
    CANCELLED = "CANCELLED"
    REJECTED = "REJECTED"
    EXPIRED = "EXPIRED"


ACTIVE = (OrderStatus.OPEN, OrderStatus.PARTIAL)


@dataclass(slots=True)
class Order:
    id: int
    book: str
    symbol: str
    side: int                      # +1 buy, -1 sell
    qty: int                       # units (not lots)
    type: OrderType = OrderType.MARKET
    limit_price: float | None = None
    stop_price: float | None = None
    product: str = "CNC"           # CNC (delivery) / MIS (intraday) / NRML (derivatives carry)
    tif: str = "DAY"               # DAY / GTC
    tag: str = ""
    group_id: int | None = None    # atomic multi-leg group: all legs fill together or not at all
    oco_group: str | None = None   # one-cancels-other
    submitted_ts: pd.Timestamp | None = None
    eligible_seq: int = 0          # first timeline index at which the order may fill
    status: OrderStatus = OrderStatus.OPEN
    filled_qty: int = 0
    filled_value: int = 0          # paise
    brokerage_paid: int = 0        # paise, for per-order brokerage caps
    triggered: bool = False        # stop-limit: stop already hit
    reason: str = ""               # reject / cancel reason
    forced: bool = False           # created by the engine (square-off, margin call), not a strategy

    @property
    def remaining(self) -> int:
        return self.qty - self.filled_qty

    @property
    def active(self) -> bool:
        return self.status in ACTIVE

    def to_dict(self) -> dict:
        return {"id": self.id, "book": self.book, "symbol": self.symbol, "side": self.side, "qty": self.qty,
                "type": self.type.value, "limit_price": self.limit_price, "stop_price": self.stop_price,
                "product": self.product, "tif": self.tif, "tag": self.tag, "group_id": self.group_id,
                "oco_group": self.oco_group, "submitted_ts": str(self.submitted_ts), "status": self.status.value,
                "filled_qty": self.filled_qty,
                "avg_fill_price": (self.filled_value / self.filled_qty / 100) if self.filled_qty else None,
                "reason": self.reason, "forced": self.forced}


@dataclass(slots=True)
class Fill:
    id: int
    order_id: int | None
    book: str
    ts: pd.Timestamp
    symbol: str
    side: int
    qty: int
    price: int                     # paise
    charges: dict = field(default_factory=dict)
    reason: str = "order"          # order / expiry / squareoff / margin_call / split_cash_in_lieu
    cash_delta: int = 0            # paise, excluding charges
    realized: int = 0              # paise, FIFO gross realised P&L generated by this fill
    tag: str = ""

    def to_dict(self) -> dict:
        return {"id": self.id, "order_id": self.order_id, "book": self.book, "ts": str(self.ts),
                "symbol": self.symbol, "side": self.side, "qty": self.qty, "price": self.price / 100,
                "charges": self.charges.get("total", 0) / 100, "charges_detail": self.charges,
                "reason": self.reason, "cash_delta": self.cash_delta / 100, "realized": self.realized / 100,
                "tag": self.tag}


@dataclass(slots=True)
class Trade:
    """A closed round trip (FIFO lot matching)."""
    book: str
    symbol: str
    direction: int
    qty: int
    entry_ts: pd.Timestamp
    entry_price: float             # rupees (per-unit, at entry; pre-split units if a split intervened)
    exit_ts: pd.Timestamp
    exit_price: float
    gross: int                     # paise
    charges: int                   # paise (entry + exit, apportioned by quantity)
    exit_reason: str = "order"
    tag: str = ""
    entry_fill: int = 0
    exit_fill: int = 0

    @property
    def net(self) -> int:
        return self.gross - self.charges

    def to_dict(self) -> dict:
        return {"book": self.book, "symbol": self.symbol, "direction": self.direction, "qty": self.qty,
                "entry_ts": str(self.entry_ts), "entry_price": self.entry_price, "exit_ts": str(self.exit_ts),
                "exit_price": self.exit_price, "gross": self.gross / 100, "charges": self.charges / 100,
                "net": self.net / 100, "exit_reason": self.exit_reason, "tag": self.tag,
                "entry_fill": self.entry_fill, "exit_fill": self.exit_fill,
                "holding_days": (self.exit_ts - self.entry_ts).total_seconds() / 86400}


@dataclass(slots=True)
class LedgerEntry:
    seq: int
    ts: pd.Timestamp
    book: str
    type: str                      # DEPOSIT / TRADE / CHARGES / MTM / SETTLEMENT / DIVIDEND / CASH_IN_LIEU
    symbol: str
    amount: int                    # signed cash movement in paise
    cash_after: int
    ref: int | None = None         # fill id
    memo: str = ""

    def to_dict(self) -> dict:
        return {"seq": self.seq, "ts": str(self.ts), "book": self.book, "type": self.type, "symbol": self.symbol,
                "amount": self.amount / 100, "cash_after": self.cash_after / 100, "ref": self.ref, "memo": self.memo}
