"""Strategy API.

A strategy is a class with `on_bar(ctx)`. It can only observe the market through `ctx`,
which exposes data up to the bar that has just closed, and it can only act by submitting
orders, which are matched against LATER bars by the execution simulator.

Strategy code never holds a reference to a broker, to the execution service, or to
process configuration.
"""
from __future__ import annotations

from typing import Any, Protocol

import numpy as np


class Context(Protocol):
    now: Any                 # pandas.Timestamp of the bar that just closed (exchange time)
    params: dict
    interval: str

    def history(self, symbol: str, field: str = "close", n: int | None = None, adjusted: bool = True) -> np.ndarray: ...
    def last(self, symbol: str, field: str = "close") -> float | None: ...
    def has_bar(self, symbol: str) -> bool: ...
    def bars_seen(self, symbol: str) -> int: ...
    def position(self, symbol: str) -> int: ...
    def positions(self) -> dict[str, int]: ...
    def entry_price(self, symbol: str) -> float: ...
    def cash(self) -> float: ...
    def equity(self) -> float: ...
    def instrument(self, symbol: str): ...
    def universe(self, kind: str = "EQ") -> list[str]: ...
    def expiries(self, underlying: str, kind: str = "OPT") -> list: ...
    def chain(self, underlying: str, expiry, kind: str = "OPT") -> list: ...
    def order(self, symbol: str, qty: int, *, type: str = "MARKET", limit: float | None = None,
              stop: float | None = None, product: str | None = None, tif: str = "DAY", tag: str = "",
              oco: str | None = None) -> int | None: ...
    def order_target(self, symbol: str, target_qty: int, **kw) -> int | None: ...
    def order_target_value(self, symbol: str, value: float, **kw) -> int | None: ...
    def multi_leg(self, legs: list[tuple[str, int]], tag: str = "") -> int | None: ...
    def cancel(self, order_id: int) -> None: ...
    def cancel_all(self, symbol: str | None = None) -> None: ...
    def open_orders(self, symbol: str | None = None) -> list: ...
    def is_last_bar_of_session(self) -> bool: ...
    def log(self, message: str) -> None: ...


class Strategy:
    """Base class. Subclasses declare `name`, `family`, `default_params`, a falsifiable
    `hypothesis`, and implement `on_bar`."""
    name = "base"
    family = "none"
    version = "1"
    hypothesis = ""
    default_params: dict = {}
    param_grid: dict = {}          # candidate values per parameter for research sweeps
    requires: str = "EQ"           # EQ | FUT | OPT — what instruments must be loaded
    intervals: tuple = ("1d",)

    def __init__(self, **params):
        unknown = set(params) - set(self.default_params)
        if unknown:
            raise ValueError(f"{self.name}: unknown parameters {sorted(unknown)}")
        self.params = {**self.default_params, **params}
        self.state: dict = {}

    def on_start(self, ctx: Context) -> None: ...
    def on_bar(self, ctx: Context) -> None: ...
    def on_fill(self, ctx: Context, fill) -> None: ...

    @classmethod
    def describe(cls) -> dict:
        return {"name": cls.name, "family": cls.family, "version": cls.version, "hypothesis": cls.hypothesis,
                "default_params": cls.default_params, "param_grid": cls.param_grid, "requires": cls.requires,
                "intervals": list(cls.intervals), "doc": (cls.__doc__ or "").strip()}
