"use client";
import Link from "next/link";
import { useEffect, useState } from "react";
import { Bars, LineChart } from "@/components/charts";
import { METRIC_HELP, MetricTiles, runCols } from "@/components/common";
import { Badge, Banner, Card, DataTable, Err, KV, Page, Synthetic } from "@/components/ui";
import { inr, num, pct, post, useApi, useQuery } from "@/lib/api";

export default function Backtest() {
  const q = useQuery();
  const strategies = useApi<any>("/strategies");
  const dss = useApi<any[]>("/datasets");
  const [f, setF] = useState({ strategy: "sma_cross", params: "{}", dataset_id: "synthetic_v1", interval: "1d", start: "", end: "", capital: 1000000, cost_multiplier: 1 });
  const [runId, setRunId] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);
  const [err, setErr] = useState<string | null>(null);
  useEffect(() => { if (q.get("run")) setRunId(q.get("run")); }, [q]);
  const det = useApi<any>(runId ? `/runs/${runId}` : null);
  const eq = useApi<any>(runId && det.data?.summary ? `/runs/${runId}/equity` : null);
  const trades = useApi<any>(runId && det.data?.summary ? `/runs/${runId}/trades` : null);
  const runs = useApi<any[]>("/runs?limit=30");
  const lib = strategies.data?.library || [], gen = strategies.data?.generated || [];
  const cur = lib.find((s: any) => s.name === f.strategy);
  const go = async () => {
    setBusy(true); setErr(null);
    try {
      const params = JSON.parse(f.params || "{}");
      const r = await post("/backtests", { dataset_id: f.dataset_id, interval: f.interval, start: f.start || null, end: f.end || null, cost_multiplier: Number(f.cost_multiplier),
        strategies: [{ name: f.strategy, params, capital: Number(f.capital) }] });
      setRunId(r.run_id); runs.reload();
    } catch (e: any) { setErr(e.message); }
    setBusy(false);
  };
  const s = det.data?.summary, m = s?.metrics;
  return (
    <Page title="Backtesting Studio" sub="Event-driven simulation: an order created on one bar can only fill on a later bar, with spread, market impact, volume limits, margin and the statutory charges in force on that date.">
      <Card title="Configure">
        <div className="row">
          <label>Strategy<select value={f.strategy} onChange={(e) => { const n = lib.find((x: any) => x.name === e.target.value); setF({ ...f, strategy: e.target.value, params: "{}", interval: n?.intervals?.[0] || "1d" }); }}>
            <optgroup label="Library">{lib.map((x: any) => <option key={x.name} value={x.name}>{x.name} ({x.family})</option>)}</optgroup>
            <optgroup label="Generated by agents (sandboxed)">{gen.map((x: any) => <option key={x.code_id} value={`generated:${x.code_id}`}>{x.hypothesis_id} ({x.family})</option>)}</optgroup></select></label>
          <label>Dataset<select value={f.dataset_id} onChange={(e) => setF({ ...f, dataset_id: e.target.value })}>{(dss.data || []).map((d) => <option key={d.dataset_id}>{d.dataset_id}</option>)}</select></label>
          <label>Interval<select value={f.interval} onChange={(e) => setF({ ...f, interval: e.target.value })}>{["1d", "1m"].map((x) => <option key={x}>{x}</option>)}</select></label>
          <label>Start<input type="date" value={f.start} onChange={(e) => setF({ ...f, start: e.target.value })} /></label>
          <label>End<input type="date" value={f.end} onChange={(e) => setF({ ...f, end: e.target.value })} /></label>
          <label>Capital (₹)<input type="number" value={f.capital} onChange={(e) => setF({ ...f, capital: Number(e.target.value) })} style={{ width: 120 }} /></label>
          <label>Cost multiplier<input type="number" step="0.5" min="0" value={f.cost_multiplier} onChange={(e) => setF({ ...f, cost_multiplier: Number(e.target.value) })} style={{ width: 90 }} /></label>
          <label style={{ flex: 1, minWidth: 200 }}>Parameters (JSON)<input value={f.params} onChange={(e) => setF({ ...f, params: e.target.value })} className="mono" /></label>
          <button className="primary" onClick={go} disabled={busy}>{busy ? "Running…" : "Run backtest"}</button>
        </div>
        {cur && <p className="dim" style={{ marginTop: 8 }}><b>Hypothesis:</b> {cur.hypothesis} <span className="mono">defaults {JSON.stringify(cur.default_params)}</span>{cur.intervals[0] !== "1d" && " · needs intraday bars (1m)"}</p>}
        {!f.start && !f.end && <p className="dim">No dates set: this run covers the whole dataset, including the sealed window. Use it for exploration, not for claims.</p>}
      </Card>
      <Err e={err || det.error} />
      {s && m && <>
        <div className="top" style={{ marginTop: 16 }}><h1>Run <span className="mono">{runId}</span></h1><Badge s={s.status} /><span className="sp" /><Link href={`/replay?run=${runId}`}>replay trades</Link><Link href={`/chat?run=${runId}`}>ask the analyst</Link></div>
        <Synthetic on={s.dataset.synthetic} />
        {s.error && <Banner tone="crit">{s.error}</Banner>}
        {s.flags.filter((x: string) => !x.startsWith("SYNTHETIC")).map((x: string) => <Banner key={x}>{x}</Banner>)}
        {s.structure_warnings?.slice(0, 4).map((x: string) => <Banner key={x} tone="info">{x}</Banner>)}
        <MetricTiles m={m} /><p className="dim" style={{ marginTop: 6 }}>{METRIC_HELP}</p>
        <div className="grid g21" style={{ marginTop: 8 }}>
          <Card title="Equity">{eq.data && <LineChart x={eq.data.ts} series={[{ name: "equity", values: eq.data.equity }]} fmt={(v) => inr(v)} />}
            <h3>Drawdown</h3>{eq.data && <LineChart x={eq.data.ts} series={[{ name: "drawdown", values: eq.data.drawdown }]} fmt={(v) => pct(v)} height={130} area zero />}</Card>
          <Card title="Lineage & checks">
            <KV items={[["strategy", s.strategies.map((x: any) => `${x.name} ${JSON.stringify(x.params)}`).join(" + ")], ["dataset", `${s.dataset.id} (${s.dataset.synthetic ? "synthetic" : "real"})`],
              ["dataset hash", <span key="d" className="mono">{s.dataset.content_hash.slice(0, 24)}…</span>], ["period", `${s.period.start} → ${s.period.end} · ${s.period.bars} bars · ${s.period.symbols} symbols`],
              ["code version", <span key="c" className="mono">{s.code_version}</span>], ["config fingerprint", <span key="f" className="mono">{s.fingerprint.slice(0, 24)}…</span>],
              ["result hash", <span key="r" className="mono">{s.result_hash.slice(0, 24)}…</span>], ["orders", Object.entries(s.orders).map(([k, v]) => `${k} ${v}`).join(" · ")],
              ["ledger reconciliation", <Badge key="b" s={s.reconciliation.ok ? "pass" : "fail"} />], ["artefacts", det.data.artefacts.join(", ")]]} />
            <h3>Charges paid</h3><Bars items={Object.entries(s.charges_breakdown).map(([label, value]) => ({ label, value: value as number }))} fmt={(v) => inr(v)} />
            <h3>Execution assumptions</h3><p className="mono dim">{Object.entries(s.execution).map(([k, v]) => `${k}=${v}`).join("  ")}</p>
          </Card>
        </div>
        <div style={{ marginTop: 14 }}><Card title={`Trades (${trades.data?.total ?? 0}) — click one to replay it`}>
          <DataTable maxHeight={360} onRow={(_, i) => { window.location.href = `/replay?run=${runId}&trade=${i}`; }} cols={[{ key: "symbol" }, { key: "direction", label: "side", f: (r) => (r.direction > 0 ? "long" : "short") }, { key: "qty", r: true },
            { key: "entry_ts", label: "entry", f: (r) => r.entry_ts.slice(0, 16) }, { key: "entry_price", label: "entry px", r: true, f: (r) => num(r.entry_price) }, { key: "exit_ts", label: "exit", f: (r) => r.exit_ts.slice(0, 16) },
            { key: "exit_price", label: "exit px", r: true, f: (r) => num(r.exit_price) }, { key: "gross", r: true, f: (r) => num(r.gross) }, { key: "charges", r: true, f: (r) => num(r.charges) },
            { key: "net", r: true, f: (r) => <span className={r.net > 0 ? "up" : "down"}>{num(r.net)}</span> }, { key: "exit_reason", label: "exit reason" }, { key: "tag" }]} rows={trades.data?.items} empty="No closed trades." />
          {s.open_positions.length > 0 && <><h3>Still open at the end (marked to market)</h3><DataTable maxHeight={160} cols={[{ key: "symbol" }, { key: "qty", r: true }, { key: "avg_price", r: true, f: (r) => num(r.avg_price) }, { key: "mark", r: true, f: (r) => num(r.mark) }, { key: "unrealized", r: true, f: (r) => num(r.unrealized) }]} rows={s.open_positions} /></>}
        </Card></div>
      </>}
      <div style={{ marginTop: 14 }}><Card title="Recent runs"><DataTable onRow={(r) => setRunId(r.run_id)} selected={(r) => r.run_id === runId} cols={runCols()} rows={runs.data} maxHeight={280} /></Card></div>
    </Page>
  );
}
