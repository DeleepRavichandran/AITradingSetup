"use client";
import { useEffect, useState } from "react";
import { MetricTiles } from "@/components/common";
import { Badge, Banner, Card, DataTable, Err, KV, Page } from "@/components/ui";
import { api, post, useApi, useQuery } from "@/lib/api";

const TEMPLATE = `"""Edit me. Allowed imports: math, numpy, nseql.indicators, nseql.strategies.api."""
from nseql import indicators as ind
from nseql.strategies.api import Strategy


class MyStrategy(Strategy):
    name = "my_strategy"
    family = "trend"
    hypothesis = "Price above its 50-day average keeps drifting up."
    default_params = {"n": 50}

    def on_bar(self, ctx):
        for s in ctx.universe("EQ"):
            c = ctx.history(s, "close", self.params["n"] + 1)
            if len(c) <= self.params["n"]:
                continue
            above = c[-1] > ind.sma(c, self.params["n"])
            if above and ctx.position(s) == 0 and not ctx.open_orders(s):
                ctx.order_target_value(s, ctx.equity() * 0.08, tag="entry")
            elif not above and ctx.position(s) > 0:
                ctx.order_target(s, 0, tag="exit")
`;

export default function Code() {
  const q = useQuery();
  const list = useApi<any>("/strategies");
  const [src, setSrc] = useState(TEMPLATE);
  const [meta, setMeta] = useState<any>(null);
  const [res, setRes] = useState<any>(null);
  const [busy, setBusy] = useState(false);
  const [err, setErr] = useState<string | null>(null);
  const load = async (kind: "code" | "lib", id: string) => {
    setRes(null); setErr(null);
    try {
      const d = await api(kind === "code" ? `/code/${id}` : `/strategies/${id}/source`);
      setSrc(d.source);
      setMeta(kind === "code" ? { kind: "generated", id, sha: d.sha256, hyp: d.hypothesis_id, gate: d.gate, validation: d.validation } : { kind: "library", id });
    } catch (e: any) { setErr(e.message); }
  };
  useEffect(() => { if (q.get("code")) load("code", q.get("code")!); else if (q.get("lib")) load("lib", q.get("lib")!); }, [q]);
  const run = async (execute: boolean) => {
    setBusy(true); setErr(null);
    try { setRes(await post("/code/validate", { source: src, run: execute })); } catch (e: any) { setErr(e.message); }
    setBusy(false);
  };
  const v = res?.validation, r = res?.run;
  return (
    <Page title="Strategy Code" sub="Read any strategy's source, or write one and test it. Code is statically checked against an allow-list and then run in a locked-down subprocess: no network, no credentials, CPU and memory limits. It can never reach an order router.">
      <Err e={err || list.error} />
      <div className="grid g21">
        <Card title={meta ? `${meta.kind}: ${meta.id}` : "Editor"} right={<span className="row"><button onClick={() => run(false)} disabled={busy}>Validate</button><button className="primary" onClick={() => run(true)} disabled={busy}>{busy ? "Running in sandbox…" : "Validate + sandbox test"}</button></span>}>
          <textarea rows={30} spellCheck={false} value={src} onChange={(e) => { setSrc(e.target.value); setRes(null); }} />
          {meta?.kind === "generated" && <KV items={[["sha256", <span key="s" className="mono">{meta.sha}</span>], ["hypothesis", meta.hyp],
            ["live gate", <span key="g"><Badge s={meta.gate.allowed ? "open" : "closed"} tone={meta.gate.allowed ? "crit" : "good"} /> {meta.gate.reasons.join("; ")}</span>]]} />}
        </Card>
        <div className="grid">
          <Card title="Open">
            <h3>Generated by agents</h3>
            <DataTable maxHeight={200} onRow={(x) => load("code", x.code_id)} cols={[{ key: "hypothesis_id", label: "hypothesis" }, { key: "family" }, { key: "status", f: (x) => <Badge s={x.status} /> }]} rows={list.data?.generated} empty="None yet." />
            <h3>Library</h3>
            <DataTable maxHeight={220} onRow={(x) => load("lib", x.name)} cols={[{ key: "name" }, { key: "family" }]} rows={list.data?.library} />
          </Card>
          {v && <Card title="Static validation"><p><Badge s={v.ok ? "pass" : "fail"} /> <span className="mono dim">{v.sha256.slice(0, 16)}</span></p>
            {v.violations.length > 0 && <ul style={{ margin: 0, paddingLeft: 18 }}>{v.violations.map((x: string) => <li key={x} className="down">{x}</li>)}</ul>}</Card>}
        </div>
      </div>
      {r && <div style={{ marginTop: 14 }}><Card title={`Sandbox test · development window ${r.window.join(" → ")}`}>
        {r.error && <Banner tone="crit">{r.error}</Banner>}
        <KV items={[["isolation", `network namespace ${r.isolation.network_namespace ? "on" : "off"} · environment scrubbed · ${r.isolation.cpu_seconds}s CPU · ${r.isolation.memory_mb} MB`],
          ["look-ahead trap", r.lookahead ? <span key="l"><Badge s={r.lookahead.passed ? "pass" : "fail"} /> {r.lookahead.orders_checked} orders compared against a run where all future values were noise</span> : "—"],
          ["flags", (r.flags || []).join(" · ") || "—"]]} />
        {r.lookahead && !r.lookahead.passed && r.lookahead.first_difference && <pre>{JSON.stringify(r.lookahead.first_difference, null, 1)}</pre>}
        <div style={{ marginTop: 10 }}><MetricTiles m={r.metrics} /></div>
      </Card></div>}
    </Page>
  );
}
